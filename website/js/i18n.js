function rulesFor(locale) {
  if (!pluralRules.has(locale)) pluralRules.set(locale, new Intl.PluralRules(locale === 'ar' ? 'ar-EG' : 'en-GB'));
  return pluralRules.get(locale);
}

export function normalizeLocale(value) {
  return value === 'en' ? 'en' : 'ar';
}

export function setLocale(locale) {
  current = normalizeLocale(locale);
  return current;
}

export function getLocale() {
  return current;
}

export function getIntlLocale(locale = current) {
  return (LOCALES[locale] || LOCALES.ar).intl;
}

export function getDir(locale = current) {
  return (LOCALES[locale] || LOCALES.ar).dir;
}

export function hasKey(key) {
  return Boolean(dictionaries[current] && key in dictionaries[current]);
}

export function t(key, params = {}) {
  const dict = dictionaries[current] || dictionaries.ar;
  const fallback = dictionaries.en;
  let value = dict[key] ?? fallback[key] ?? key;
  if (params && typeof value === 'string') {
    value = value.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
  }
  return value;
}

/**
 * Plural-aware lookup: picks `key_<category>` using Intl.PluralRules.
 * Falls back to `key_other` then `key`.
 */
export function tp(key, count, params = {}) {
  const category = rulesFor(current).select(count);
  const candidate = `${key}_${category}`;
  const dict = dictionaries[current] || dictionaries.ar;
  if (candidate in dict) return t(candidate, { ...params, n: count });
  if (`${key}_other` in dict) return t(`${key}_other`, { ...params, n: count });
  return t(key, { ...params, n: count });
}

export function pluralCategory(count, locale = current) {
  return rulesFor(locale).select(count);
}

/** Applies translations to every [data-i18n] and [data-i18n-attr] node in `root`. */
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.getAttribute('data-i18n');
    const params = node.dataset.i18nParams ? safeParse(node.dataset.i18nParams) : {};
    node.textContent = t(key, params);
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((node) => {
    const spec = node.getAttribute('data-i18n-attr');
    spec.split(',').forEach((pair) => {
      const [attr, key] = pair.split(':').map((part) => part.trim());
      if (attr && key) {
        const params = node.dataset.i18nParams ? safeParse(node.dataset.i18nParams) : {};
        node.setAttribute(attr, t(key, params));
      }
    });
  });
  root.querySelectorAll('[data-i18n-title]').forEach((node) => {
    node.setAttribute('title', t(node.getAttribute('data-i18n-title')));
  });
}

function safeParse(json) {
  try {
    return JSON.parse(json);
  } catch {
    return {};
  }
}

